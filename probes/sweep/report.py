#!/usr/bin/env python3
"""One table of every recorded agent run of the sweep task, from results/sweep/agent-runs/*.summary.json.

    python3 probes/sweep/report.py              # print the tables
    python3 probes/sweep/report.py --write      # also write results/sweep/agent-runs/README.md

Runs are grouped by model, setting and level. Runs on different builds of the task are not comparable:
the `commit` column says which build each run used. Runs with no score (the harness failed) are listed
separately and never counted as a score of 0.
"""
import collections, glob, json, os, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from models import ROOT  # noqa: E402

KEEP = os.path.join(ROOT, "results", "sweep", "agent-runs")


def main():
    runs = [json.load(open(f)) for f in sorted(glob.glob(os.path.join(KEEP, "*.summary.json")))]
    scored = [r for r in runs if r.get("score") is not None]
    out = ["# Sweep task: recorded agent runs", "",
           f"{len(scored)} scored runs, {len(runs) - len(scored)} without a score. Generated by `python3 probes/sweep/report.py --write`.", ""]
    groups = collections.defaultdict(list)
    for r in scored:
        groups[(r["model"], r["setting"], r["level"])].append(r)
    out += ["## By model, setting and level", "", "| Model | Setting | Level | Runs | Seeds | Scores | Mean | Builds |", "|---|---|---|---|---|---|---|---|"]
    for (model, setting, level), rs in sorted(groups.items()):
        scores = [r["score"] for r in rs]
        out.append(f"| {model} | {setting} | {level} | {len(rs)} | {' '.join(str(r['seed']) for r in rs)} | {' / '.join(f'{s:.2f}' for s in scores)} "
                   f"| {sum(scores) / len(scores):.2f} | {', '.join(sorted({str(r.get('commit')) for r in rs}))} |")
    out += ["", "## Every run", "", "| Run | Score | Trash in bin | Mistakes | Milestones reached | Tool calls | Robot time (s) | Minutes | Cost (USD) | Build |", "|---|---|---|---|---|---|---|---|---|---|"]
    for r in runs:
        score = "no score" if r.get("score") is None else f"{r['score']:.2f}"
        cost = "-" if r.get("cost_usd") is None else f"{r['cost_usd']:.2f}"
        out.append(f"| {r['run']} | {score} | {r.get('trash_in_bin')} | {len(r.get('mistakes') or [])} | {', '.join((r.get('milestones') or {}).keys()) or '-'} "
                   f"| {r.get('tool_calls')} | {r.get('robot_time_s')} | {r.get('minutes')} | {cost} | {r.get('commit')} |")
    text = "\n".join(out) + "\n"
    print(text)
    if "--write" in sys.argv:
        os.makedirs(KEEP, exist_ok=True)
        open(os.path.join(KEEP, "README.md"), "w").write(text)


if __name__ == "__main__":
    main()
